/// <summary>
/// 植物的状态。定死，不开放给数据自定义——
/// 所有组件都靠"现在是什么状态"来决定自己该不该干活。
///
/// 注意："害怕待机""残血待机"这些**不是状态**，它们是同一个待机状态下的不同表现，
/// 由动画组自己按血量 / 位置去挑。状态只表达"能不能干活"这一层。
/// </summary>
public enum PlantState
{
    /// <summary>待机：没什么可干的。</summary>
    Idle,

    /// <summary>攻击：这一路上有僵尸，该干活了。**只能由攻击管理改。**</summary>
    Attack,

    /// <summary>正在倒下（动画还没播完，还没从格子上拿掉）。</summary>
    Die,

    /// <summary>彻底没了，终点。</summary>
    Dead,
}
